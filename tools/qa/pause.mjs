import { chromium } from 'playwright-core';
import fs from 'node:fs';
fs.mkdirSync('tools/qa/out', { recursive: true });
const edge = 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe';
const b = await chromium.launch({ executablePath: edge, headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1280, height: 720 } });
const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type()==='error') errs.push(m.text()); });
await p.goto('http://127.0.0.1:8010/', { waitUntil: 'networkidle' });
await p.waitForSelector('#loading.hidden', { timeout: 30000 }).catch(()=>{});
await p.waitForTimeout(500);
await p.screenshot({ path: 'tools/qa/out/720-menu.png' });
await p.click('#btn-start'); await p.waitForTimeout(1600); await p.click('#story-skip'); await p.waitForTimeout(700); await p.click('#btn-enter'); await p.waitForTimeout(1200);
console.log('locked', await p.evaluate(()=>!!document.pointerLockElement));
await p.keyboard.press('Escape'); await p.waitForTimeout(800);
console.log('after esc', await p.evaluate(()=>({state:window.__game.state, pauseHidden:document.getElementById('pause').classList.contains('hidden')})));
await p.screenshot({ path: 'tools/qa/out/720-pause.png' });
await p.click('#btn-resume'); await p.waitForTimeout(800);
console.log('after resume', await p.evaluate(()=>({state:window.__game.state, locked:!!document.pointerLockElement})));
await p.keyboard.down('w'); await p.waitForTimeout(900); await p.keyboard.up('w');
console.log('pos', await p.evaluate(()=>[window.__game.player.position.x.toFixed(1), window.__game.player.position.z.toFixed(1)]));
console.log('audio', await p.evaluate(()=>({buffers:window.__game.audio.buffers.size, state:window.__game.audio.ctx.state, music:window.__game.audio.musicKey, voDurations:[1,2,3,4,5].map(i=>+window.__game.audio.duration('vo_0'+i).toFixed(2)), sum:+([1,2,3,4,5].reduce((s,i)=>s+window.__game.audio.duration('vo_0'+i),0)).toFixed(2)})));
console.log('errors', errs);
await b.close();
